"""Writes src/pe_decode.sv from the instruction table, so the table is the one source.

Usage: gen_decode.py [table.md] [output.sv]

The table sits between the isa-table markers. Each row has six columns: syntax, encoding,
fields, slots, W and semantics. Only the first five are read here.
"""
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
TABLE = os.path.join(ROOT, 'docs', 'ISA.md')
OUTPUT = os.path.join(ROOT, 'src', 'pe_decode.sv')

PORT_A = 'ndr'      # register letters read on port A
PORT_B = 'sat'      # register letters read on port B


class Row:
    def __init__(self, cells):
        self.syntax = cells[0].strip('`')
        self.enc = cells[1].strip('`').replace(' ', '')
        self.types = dict(f.split(':') for f in cells[2].strip('`').split())
        self.world = cells[4]
        if len(self.enc) != 16:
            raise ValueError('encoding is not 16 bits: ' + self.syntax)
        self.fields = {}
        for i, ch in enumerate(self.enc):
            if ch not in '01':
                self.fields.setdefault(ch, []).append(15 - i)
        if set(self.fields) != set(self.types):
            raise ValueError('fields differ from the encoding: ' + self.syntax)
        text = self.syntax.replace(' [, inbox]', '').split(None, 1)
        self.mn = text[0]
        self.ops = [o.strip() for o in text[1].split(',')] if len(text) > 1 else []
        self.name = ''

    def select(self, letter):
        bits = self.fields[letter]
        return 'word[%d:%d]' % (bits[0], bits[-1])


def read_table(path):
    with open(path) as fh:
        body = fh.read().split('<!-- isa-table-begin -->')[1].split('<!-- isa-table-end -->')[0]
    rows = []
    for line in body.strip().splitlines():
        cells = [c.strip() for c in re.split(r'(?<!\\)\|', line)[1:-1]]
        if len(cells) == 6 and cells[0].startswith('`'):
            rows.append(Row(cells))
    return rows


def name_rows(rows):
    """OP_ADD, or OP_PUT_NT where a mnemonic has several rows: the operands that differ name the row."""
    groups = {}
    for r in rows:
        groups.setdefault(r.mn, []).append(r)
    for mn, group in groups.items():
        longest = max(len(r.ops) for r in group)
        for r in group:
            parts = [mn.upper()]
            for k in range(longest):
                here = {x.ops[k] if k < len(x.ops) else '' for x in group}
                if len(here) > 1 and k < len(r.ops):
                    parts.append(r.ops[k].replace('!', 'N').replace('^', 'X').upper())
            r.name = 'OP_' + '_'.join(parts)
    if len({r.name for r in rows}) != len(rows):
        raise ValueError('two rows got one name')


def illegal_test(r):
    tests = []
    for letter, ty in sorted(r.types.items()):
        v = r.select(letter)
        if ty == 'opin':
            tests.append("%s == 4'd3" % v)
        elif ty == 'iopin':
            tests.append("!%s" % ('word[%d]' % r.fields[letter][0]))
        elif ty == 'lane':
            tests.append("word[%d] || (%s != 4'd0 && %s < 4'd4)" % (r.fields[letter][0], v, v))
        elif ty == 'wmode':
            tests.append("%s == 2'd3" % v)
    return ' || '.join(tests) if tests else None


def world_expr(r):
    if r.world == 'pin':
        return "(%s != 4'd0) || (%s != 4'd3)" % (r.select('i'), r.select('o'))
    return "1'b1" if r.world == 'y' else "1'b0"


def reg_field(r, letters):
    for letter in letters:
        if r.types.get(letter) in ('reg', 'reg4'):
            s = r.select(letter)
            return s if r.types[letter] == 'reg' else "{1'b0, %s}" % s
    return None


def generate(rows, table_name):
    op_bits = len(bin(len(rows) - 1)) - 2
    out = []
    w = out.append
    w('/*')
    w(' * Instruction decoder. Generated by tools/gen_decode.py from %s. Do not edit.' % table_name)
    w(' * A word that matches no row, or has a value its field forbids, reads as illegal.')
    w(' * SPDX-License-Identifier: Apache-2.0')
    w(' */')
    w('')
    w('`default_nettype none')
    w('')
    w('package pe_op_pkg;')
    w('')
    w('  localparam int unsigned OP_BITS = %d;' % op_bits)
    w('')
    width = max(len(r.name) for r in rows)
    for i, r in enumerate(rows):
        w("  localparam logic [%d:0] %s = %d'd%d;" % (op_bits - 1, r.name.ljust(width), op_bits, i))
    w('')
    w('endpackage')
    w('')
    w('module pe_decode')
    w('  import pe_op_pkg::*;')
    w('(')
    w('    input  logic [15:0]        word,')
    w('    output logic [OP_BITS-1:0] op,')
    w('    output logic               illegal,')
    w('    output logic               world,')
    w('    output logic [2:0]         ra,       // register read on port A')
    w('    output logic [2:0]         rb        // register read on port B')
    w(');')
    w('')
    w('  always_comb begin')
    w('    op      = OP_IDLE;')
    w("    illegal = 1'b1;")
    w("    world   = 1'b0;")
    w('    ra      = word[11:9];')
    w('    rb      = word[8:6];')
    w('    casez (word)')
    for r in rows:
        pat = ''.join(c if c in '01' else '?' for c in r.enc)
        w("      16'b%s: begin  // %s" % (pat, r.syntax))
        w('        op      = %s;' % r.name)
        test = illegal_test(r)
        w("        illegal = %s;" % (test if test else "1'b0"))
        w('        world   = %s;' % world_expr(r))
        a, b = reg_field(r, PORT_A), reg_field(r, PORT_B)
        if a:
            w('        ra      = %s;' % a)
        if b:
            w('        rb      = %s;' % b)
        w('      end')
    w('      default: ;')
    w('    endcase')
    w('  end')
    w('')
    w('endmodule')
    return '\n'.join(out) + '\n'


def main():
    table = sys.argv[1] if len(sys.argv) > 1 else TABLE
    output = sys.argv[2] if len(sys.argv) > 2 else OUTPUT
    rows = read_table(table)
    name_rows(rows)
    with open(output, 'w') as fh:
        fh.write(generate(rows, 'docs/ISA.md'))
    print('%d rows, %s' % (len(rows), os.path.normpath(output)))


if __name__ == '__main__':
    main()
