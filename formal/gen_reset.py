#!/usr/bin/env python3
"""Writes reset_flops.sv and probes_reset.ys, the checks of section 8 on every flop of the chip.

Usage: gen_reset.py <chip.json> <out folder>

<chip.json> is the chip as read_chip.ys reads it, after proc (yosys write_json; reset_flops.ys makes it).
The script first checks the structure, and stops with an error if any of these fails:
  - every flop is an asynchronous-load flop ($aldff) with a constant load value, active low;
  - its load comes from rst_n itself (the reset synchroniser) or from the synchronised reset core.rst_n_sync;
  - its value under reset is the value section 8 gives: 0, except the two window points of each shift
    unit, p - p/4 = 192 and p - p/2 = 128 for p = 256 (section 5.9.6, implementation note).
Then it writes a wrapper that asserts, for every flop, that it holds that value in every cycle of reset and
in the first cycle after reset ends (cycle 0, section 3.1), and the probes that connect it.
SPDX-License-Identifier: Apache-2.0
"""
import json
import re
import sys

# Section 8: every flop resets to 0, with these exceptions (section 5.9.6, implementation note).
SPEC_NONZERO = {r"core\.gen_shift\[\d\]\.shift\.pwq_q": 192, r"core\.gen_shift\[\d\]\.shift\.pwh_q": 128}


def spec_value(name):
    for pat, val in SPEC_NONZERO.items():
        if re.fullmatch(pat, name):
            return val
    return 0


def main():
    src, out = sys.argv[1], sys.argv[2]
    mod = json.load(open(src))["modules"]["tt_um_sarkar22_pe"]
    nets = mod["netnames"]
    rst_pad = nets["rst_n"]["bits"]
    rst_core = nets["core.rst_n_sync"]["bits"]
    # slang joins a port to its connection with a $buf cell: follow those back to the driver.
    buf = {}
    for cell in mod["cells"].values():
        if cell["type"] == "$buf":
            for a, y in zip(cell["connections"]["A"], cell["connections"]["Y"]):
                buf[y] = a

    where = {}
    for name, net in sorted(nets.items()):
        if not name.startswith("$"):
            for i, b in enumerate(net["bits"]):
                if b not in ("0", "1", "x", "z"):
                    src = b
                    while src in buf:
                        src = buf[src]
                    where.setdefault(src, (name, i))

    def slice_of(q):
        places = [where.get(b) for b in q]
        if None in places or len({n for n, _ in places}) != 1:
            return None
        lo = places[0][1]
        if [i for _, i in places] != list(range(lo, lo + len(q))):
            return None
        return f"{places[0][0]}[{lo + len(q) - 1}:{lo}]"

    def source(bits):
        out = []
        for b in bits:
            while b in buf:
                b = buf[b]
            out.append(b)
        return out
    by_bits = {}
    for name, net in sorted(nets.items()):
        if not name.startswith("$"):
            by_bits.setdefault(tuple(net["bits"]), name)
    errors, flops = [], []
    for cname, cell in sorted(mod["cells"].items()):
        t = cell["type"]
        if t in ("$aldff",):
            pass
        elif re.search(r"ff|latch|\$sr$|mem", t):
            errors.append(f"{cname}: flop type {t} has no asynchronous reset")
            continue
        else:
            continue
        p, c = cell["parameters"], cell["connections"]
        if int(p["ALOAD_POLARITY"], 2) != 0:
            errors.append(f"{cname}: reset is active high")
        if any(b not in ("0", "1") for b in c["AD"]):
            errors.append(f"{cname}: reset value is not a constant")
            continue
        if source(c["ALOAD"]) == source(rst_pad):
            group = "pad"
        elif source(c["ALOAD"]) == source(rst_core):
            group = "core"
        else:
            errors.append(f"{cname}: reset comes from neither rst_n nor core.rst_n_sync")
            continue
        q = tuple(c["Q"])
        name = by_bits.get(q)
        if name is None:
            # An array element: its outputs reach a slice of the array's wire through $buf cells.
            name = slice_of(q)
        if name is None:
            errors.append(f"{cname}: no wire carries exactly its outputs")
            continue
        rv = sum(int(b) << i for i, b in enumerate(c["AD"]))
        if rv != spec_value(name):
            errors.append(f"{name}: resets to {rv}, section 8 says {spec_value(name)}")
        flops.append((name, len(q), rv, group))
    if errors:
        print("\n".join(errors))
        sys.exit(1)
    nbits = sum(w for _, w, _, _ in flops)
    sv = ["/*",
          " * Generated by gen_reset.py from the chip as slang reads it. Do not edit; run.sh checks it is current.",
          f" * {len(flops)} flops, {nbits} bits. Section 8: reset is asynchronous on every flop, and after it every",
          " * flop holds its reset value. The checks: in every cycle of reset, and in cycle 0, the first cycle after",
          " * the synchronised reset ends (sections 3.1 and 9.1), each flop holds the value section 8 gives.",
          " * SPDX-License-Identifier: Apache-2.0",
          " */", "", "`default_nettype none", "",
          "module reset_flops (", "    input wire       clk,", "    input wire       rst_n,", "    input wire       ena,",
          "    input wire [7:0] ui_in,", "    input wire [7:0] uio_in", ");", "",
          "  wire [7:0] uo_out, uio_out, uio_oe;", "",
          "  tt_um_sarkar22_pe dut (.ui_in(ui_in), .uo_out(uo_out), .uio_in(uio_in), .uio_out(uio_out), .uio_oe(uio_oe),",
          "                        .ena(ena), .clk(clk), .rst_n(rst_n));", "",
          "  wire rst_ok;  // core.rst_n_sync, the core's reset after the synchroniser", ""]
    probes = ["# Generated by gen_reset.py: the probes of reset_flops.sv.",
              "connect -nomap -nounset -set rst_ok dut.core.rst_n_sync"]
    for i, (name, w, rv, group) in enumerate(flops):
        sv.append(f"  wire [{w - 1}:0] f{i};  // {name}")
        probes.append(f"connect -nomap -nounset -set f{i} dut.{name}")
    sv += ["", "  always @* if ($initstate) assume (!rst_n);", "",
           "  reg p_rst_ok = 1'b1;", "  always @(posedge clk) p_rst_ok <= rst_ok;", "",
           "  wire cycle0 = !$initstate && !p_rst_ok && rst_ok;", "",
           "  always @* begin"]
    for i, (name, w, rv, group) in enumerate(flops):
        cond = "!rst_n" if group == "pad" else "(!rst_ok || cycle0)"
        sv.append(f"    if ({cond}) assert (f{i} == {w}'d{rv});")
    sv += ["  end", "",
           "  // Covers: reset ends, and in cycle 0 the pads show section 8: every uio pad undriven, every uo pin low.",
           "  always @* begin",
           "    cover (cycle0);",
           "    if (cycle0) begin",
           "      cycle0_uio_oe: assert (uio_oe == 8'h00);",
           "      cycle0_uo: assert (uo_out == 8'h00);",
           "      cover (uio_oe == 8'h00 && uo_out == 8'h00);",
           "    end",
           "  end", "", "endmodule", "", "`default_nettype wire", ""]
    open(f"{out}/reset_flops.sv", "w").write("\n".join(sv))
    open(f"{out}/probes_reset.ys", "w").write("\n".join(probes) + "\n")
    print(f"{len(flops)} flops, {nbits} bits: every flop resets asynchronously to the value of section 8")


main()
