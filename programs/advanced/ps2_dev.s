; PS/2 device, keyboard style. Both lines open drain. Clock 12.5 kHz: 40 us low, about 40 us high.
; MIN: bytes to send to the PS/2 host. MOUT: bytes the PS/2 host sent, 0x1nn if parity was bad.
; Answers on its own: FF reset, F2 identify, EE echo, FE resend, anything else FA.
.equ CK io3
.equ DT io2
.equ MIN 0
.equ MOUT 1
start:  pcfg  CK, OD
        pcfg  DT, OD
        now
        li    R3, 1000      ; 20 us for the clock to rise on a slow bus
loop:   until CK, 0, inbox  ; T=1 the host pulled clock low, T=0 a byte is waiting
        jt    hold
        recv  R5, MIN
go:     call  xmit
        goto  loop
hold:   until CK, 1
        get   DT
        jt    loop          ; only an inhibit
        call  rx
        jf    badp
        send  R0, MOUT
        cmpi  R0, 0xFE
        jt    go            ; resend the last byte
        ldi   R5, 0xEE
        cmpi  R0, 0xEE
        jt    go            ; echo
        ldi   R5, 0xFA
        cmpi  R0, 0xFF
        jt    rst
        cmpi  R0, 0xF2
        jf    go            ; everything else, LED masks included
        call  xmit
        ldi   R5, 0xAB
        call  xmit
        ldi   R5, 0x83
        goto  go
rst:    call  xmit
        ldi   R5, 0xAA
        goto  go
badp:   cp    R6, R0
        lui   R6, 1
        send  R6, MOUT
        ldi   R5, 0xFE
        goto  go
; send R5. Host inhibit or request-to-send aborts it; it restarts when the host is done.
xmit:   cp    R2, R7
retry:  until CK, 1
        now
        li    R1, 2500      ; clock must have been high 50 us
        until CK, 0, R1
        jt    retry
        ldi   R6, 1         ; odd parity
        now
        cp    R0, R5
        clrt
        call  ckbit
        jf    abort
        ldi   R1, 8
xb:     shr8  R0, -, -
        call  ckbit
        jf    abort
        djnz  R1, xb
        bt    R6, 0
        call  ckbit
        jf    abort
        sett
        call  ckbit         ; T ignored: a hold after the 11th fall needs no resend
        jr    R2
abort:  put   DT, 1
        put   CK, 1
        now
        until CK, 1
        get   DT
        jt    retry         ; inhibit over: send it again
        call  rx            ; the host wants the bus; take its byte, then resend ours
        send  R0, MOUT
        goto  retry
; one bit, T = value. Data moves 15 us after clock rise, clock falls at 40 us, released at 80 us.
; T=1 back if the clock really rose, and D is that rise.
ckbit:  put   DT, T
        bx    R6, 0
        bs    R6, 0
        tick  750
        put   CK, 0
        tick  1250
        get   CK            ; the snapshot of our own fall: low already means the host got there first
        jf    abort
        put   CK, 1
        tick  2000
        until CK, 1, R3
        ret
; one clock pulse generated by us
rclk:   put   CK, 0
        tick  2000
        put   CK, 1
        tick  2000
        get   DT            ; T = data as the clock rose; stalls on that tick
        ret
; host to device. R0 = byte, T=1 if parity is good
rx:     cp    R4, R7
        now
        ldi   R0, 0
        ldi   R1, 8
        ldi   R6, 1
rb:     call  rclk
        shr8  R0, DT, -
        get   DT
        bx    R6, 0
        bs    R6, 0
        djnz  R1, rb
        call  rclk          ; parity
        bx    R6, 0
        bs    R6, 0
        call  rclk          ; stop, the host has let go
        put   DT, 0
        tick  750           ; our ACK
        put   CK, 0
        tick  1250
        put   CK, 1
        put   DT, 1
        tick  2000
        bn    R6, 0
        jr    R4
